import { useStore } from './store';

/** Коды (Э1, Б, M1, К1) нужны для прослеживаемости — показываем их только в режиме обоснования. */
export function useCodes() {
  return useStore().trace;
}

export const code = (c: string, text: string, show: boolean) => (show ? `${c} · ${text}` : text);

/** Убирает код инициативы из подписи вида «Б · напоминания». */
export const stripCode = (label: string, show: boolean) => {
  if (show) return label;
  const t = label.replace(/^[А-ЯЁ](-[А-ЯЁ])? · /, '');
  return t.charAt(0).toUpperCase() + t.slice(1);
};

export const critCode = (id: string) => id.replace('K', 'К');

